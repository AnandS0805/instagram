const fs = require('fs');
const path = require('path');

let supabaseUrl = process.env.SUPABASE_URL || '';
let supabaseAnonKey = process.env.SUPABASE_ANON_KEY || '';

// Fallback to local .env if running locally without process environment variables set
if (!supabaseUrl && fs.existsSync(path.join(__dirname, '.env'))) {
  const envContent = fs.readFileSync(path.join(__dirname, '.env'), 'utf8');
  envContent.split('\n').forEach(line => {
    const trimmed = line.trim();
    if (trimmed && !trimmed.startsWith('#')) {
      const [key, ...rest] = trimmed.split('=');
      const val = rest.join('=').trim().replace(/^["']|["']$/g, '');
      if (key.trim() === 'SUPABASE_URL') supabaseUrl = val;
      if (key.trim() === 'SUPABASE_ANON_KEY') supabaseAnonKey = val;
    }
  });
}

const content = `// Auto-generated by build.js during deployment / local build
window.__ENV = {
  SUPABASE_URL: ${JSON.stringify(supabaseUrl)},
  SUPABASE_ANON_KEY: ${JSON.stringify(supabaseAnonKey)}
};
`;

fs.writeFileSync(path.join(__dirname, 'env.js'), content, 'utf8');
console.log('Successfully generated env.js!');
